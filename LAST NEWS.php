        <h1>LATEST NEWS</h1>
        <h3>1. SecondsAgo Achieves Record Sales in Refurbished Equipment (October 2025)</h3>
        <p>The company has exceeded sales of 10,000 refurbished computers and laptops in the last quarter.
        This growth reflects the increasing demand for sustainable and affordable technology. The CEO, Iker Mendizabal, 
        emphasized that "each refurbished device is another step towards a greener future."</p>
        <h3>2. SecondsAgo Opens New Center in Vitoria-Gasteiz (September 2025)</h3>
        <p>SecondsAgo has inaugurated its second recycling center in Vitoria-Gasteiz for the treatment of old electronic equipment. 
        The new center will have the capacity to process more than 30 tons of technological waste per month, 
        and will ensure proper management of materials (copper, aluminum, and plastics).</p>
        <h3>3. Collaboration with Schools: "Renew Your Classroom" Project (August 2025)</h3>
        <p>The company has launched the "Renew Your Classroom" program, with the aim of donating refurbished computers 
        to schools in the Basque Country and Navarra. 
        Through this initiative, they aim to reduce the digital divide and promote the reuse of computer equipment, avoiding disposal.</p>
        <h3>4. SecondsAgo Receives "Green Company of the Year" Award (July 2025)</h3>
        <p>At the GreenTech Summit event, SecondsAgo received the "Green Company of the Year" award for its commitment to the environment and 
        its innovative circular economy-based model. 
        The company intends to continue combining sustainability and innovation in the future.</p>
