        <h2>ABOUT US</h2>
       <p>SecondsAgo is an innovative Basque company, specialized in the refurbishment, sale and recycling of IT products. 
        Founded in 2018, its goal is clear: to give technology a second life and actively participate in environmental care.</p>

       <p>The company's philosophy is based on this idea: 
        many of the IT devices that are discarded today can still be useful. 
        That's why SecondsAgo collects computers, mobile phones, screens and other components from companies, 
        public organizations and individuals, and carries out a complete refurbishment process with them. <br>
        <img src="https://www.goodram.com/wp-content/uploads/20230223_144834-1-scaled.jpg" class="testuArgazki1" width="350" height="300"> <br>
        In this process, expert technicians examine the devices, replace damaged parts and 
        finally prepare the product for remarketing, with quality guarantee.</p>

       <p>When refurbishment is not possible, SecondsAgo doesn't waste any materials. 
        They disassemble the devices and separate the recyclable materials (copper, aluminum, plastics...), 
        and send them to authorized recycling facilities. This way, the environmental impact is minimized 
        and they promote the circular economy.</p>

       <p>The company focuses on sustainability, but also on technological innovation. 
        Year after year, the refurbishment processes have been improved, and today they use automated diagnostic and 
        cleaning systems to effectively evaluate the condition of each product.</p>

        <img src="https://i0.wp.com/elinformaticopersonal.com/wp-content/uploads/2023/12/Tienda-el-informatico-personal-2-1-1536x768-1.jpg?fit=800%2C400&ssl=1" class="testuArgazki2" width="350" height="350">

       <p>Furthermore, SecondsAgo also emphasizes its commitment to education and society. 
        It collaborates with vocational training schools in the Basque Country, 
        offering internship opportunities to students and showing the importance of sustainability. 
        In addition, the company organizes social campaigns every year, reminding society 
        of the importance of using technology responsibly.</p> 

       <p>What started as just a small workshop, today has become a reference in the 
        northern Basque Country and northwestern Spain. 
        SecondsAgo has its own online store, where customers can purchase refurbished computers, 
        phones and IT accessories, always with guaranteed quality and reliability.</p>

       <p>Their message is clear and matches their name:</p>

       <p>SecondsAgo - Technology deserves a second chance.</p>

